def encode(art):
    assert len(art) == H, art
    bits = 0
    for row, line in enumerate(art):
        assert len(line) == W, line
        for col, ch in enumerate(line):
            if ch == "#":
                bits |= 1 << (row * W + col)
    return bits


def decode(bits):
    return ["".join("#" if bits >> (row * W + col) & 1 else "." for col in range(W)) for row in range(H)]


def render_table():
    n = len(GLYPHS)
    out = [f"const int GLYPH_COUNT = {n};", "", f"uint glyphs[{n}] = uint[{n}]("]
    for i, (label, art) in enumerate(GLYPHS):
        sep = "," if i < n - 1 else " "
        out.append(f"    uint(0x{encode(art):08x}u){sep}  // {i:2}: {label}")
    out.append(");")
    return "\n".join(out) + "\n"


def main():
    if "--decode" in sys.argv:
        for i, (label, art) in enumerate(GLYPHS):
            assert decode(encode(art)) == art
            print(f"{i:2} {label}")
            print("\n".join("   " + r for r in art))
        return
    table = render_table()
    if "--write" in sys.argv:
        path = Path(__file__).resolve().parent.parent / "shaders" / "terminal.frag"
        src = path.read_text()
        pattern = re.compile(r"(// BEGIN GLYPH TABLE[^\n]*\n).*?(// END GLYPH TABLE)", re.S)
        if not pattern.search(src):
            sys.exit("markers not found in terminal.frag")
        path.write_text(pattern.sub(lambda m: m.group(1) + table + m.group(2), src))
        print(f"wrote {len(GLYPHS)} glyphs to {path}")
    else:
        sys.stdout.write(table)


if __name__ == "__main__":
    main()
